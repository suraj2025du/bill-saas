const ALL: Record<LabelLanguage, Labels> = { en: EN, hi: HI, ta: TA, mr: MR, bn: BN };

/** Labels in the chosen language; bilingual shows "Local / English". */
export function labelsFor(language: LabelLanguage, bilingual: boolean): Labels {
  const local = ALL[language] ?? EN;
  if (language === 'en' || !bilingual) return local;
  const out = {} as Labels;
  for (const k of Object.keys(EN) as LabelKey[]) out[k] = local[k] === EN[k] ? EN[k] : `${local[k]} / ${EN[k]}`;
  return out;
}

export function docTitle(labels: Labels, type: DocType): string {
  return labels[type];
}

/** "Invoice No." changes with the document type. */
export function numberLabel(labels: Labels, type: DocType, language: LabelLanguage): string {
  if (language !== 'en') return labels.docNo;
  switch (type) {
    case 'QUOTATION':
      return 'Quotation No.';
    case 'PROFORMA':
      return 'Proforma No.';
    case 'CREDIT_NOTE':
      return 'Credit Note No.';
    case 'DEBIT_NOTE':
      return 'Debit Note No.';
    case 'DELIVERY_CHALLAN':
      return 'Challan No.';
    case 'BILL_OF_SUPPLY':
      return 'Bill No.';
    default:
      return labels.docNo;
  }
}
